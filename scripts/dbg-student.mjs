import { chromium } from 'playwright';
const b = await chromium.launch();
const ca = await b.newContext({ viewport: { width: 1366, height: 820 } });
const cb = await b.newContext({ viewport: { width: 390, height: 780 }, isMobile: true, hasTouch: true });
const t = await ca.newPage(); const s = await cb.newPage();
s.on('pageerror', (e) => console.log('S ERR', e.message)); t.on('pageerror', (e) => console.log('T ERR', e.message));
const id = 'dbs' + Date.now().toString(36); const WS = encodeURIComponent('ws://localhost:1234');
await t.goto(`http://localhost:4173/#/b/${id}?r=t&st=7&srv=${WS}`); await t.waitForSelector('.board-doc'); await t.waitForTimeout(500);
await s.goto(`http://localhost:4173/#/b/${id}?r=s&srv=${WS}`); await s.waitForSelector('.board-doc'); await s.waitForTimeout(1000);
await t.keyboard.type('추석 : festival');
await t.waitForTimeout(500);
await t.evaluate(() => window.__kwd.store.setSetting('studentWrite', true));
await s.waitForTimeout(800);
console.log('editable', await s.evaluate(() => window.__kwd.editor().isEditable));
await s.evaluate(() => window.__kwd.editor().commands.focus('end'));
console.log('active', await s.evaluate(() => document.activeElement.className));
await s.keyboard.press('Enter');
await s.waitForTimeout(100);
console.log('after enter', JSON.stringify(await s.evaluate(() => window.__kwd.editor().getJSON())));
await s.keyboard.type('학생이 씁니다', { delay: 30 });
await s.waitForTimeout(500);
console.log('S text', JSON.stringify(await s.evaluate(() => window.__kwd.editor().getText())));
console.log('T text', JSON.stringify(await t.evaluate(() => window.__kwd.editor().getText())));
await b.close();
