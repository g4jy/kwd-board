import { chromium } from 'playwright';
import fs from 'node:fs';
const B = 'https://g4jy.github.io/kwd-board/';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1366, height: 820 } });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto(B);
await p.fill('.new-board input', '1000001'); await p.click('button:has-text("새 수업")');
await p.waitForFunction(() => window.__kwd);
await p.waitForFunction(() => document.activeElement?.closest?.('.ProseMirror'), null, { timeout: 10000 });
await p.keyboard.type('추석에 가족이 모여요.');
const before = await p.textContent('.page-text .board-doc');
const [ch] = await Promise.all([p.waitForEvent('filechooser'), p.click('.toolbar [data-tool="import"]').then(() => p.click('.menu button:has-text("PDF")'))]);
await ch.setFiles('tests/fixtures/slides.pdf');
await p.waitForFunction(() => window.__kwd.pages().length === 4, null, { timeout: 30000 });
await p.click('.tb-pens > * >> nth=1');
await p.mouse.move(500, 400); await p.mouse.down(); await p.mouse.move(720, 410, { steps: 8 }); await p.mouse.up();
await p.reload(); await p.waitForFunction(() => window.__kwd && window.__kwd.pages().length === 4, null, { timeout: 15000 });
const text = await p.textContent('.page-text .board-doc');
await p.screenshot({ path: '/tmp/live.png' });
const ink = await p.evaluate(() => window.__kwd.pages().map((x) => window.__kwd.store.doc.getArray('ink:' + x.id).length));
console.log(JSON.stringify({ ink, before, text, pages: await p.evaluate(() => window.__kwd.pages().length), errs }));
await b.close();
