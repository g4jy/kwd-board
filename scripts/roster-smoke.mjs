// 학생 표: 체험 폴더의 _roster.json → 목적 × 단계 표, 지금/모두, 찾기, 카드 누르면 그 학생 판
import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = process.env.BASE || 'http://localhost:4173';
const OUT = process.env.OUT || 'test-results/roster';
fs.mkdirSync(OUT, { recursive: true });
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
const res = {};
await p.goto(`${BASE}/#/`);
await p.waitForSelector('.home');
await p.click('.home-demo');
await p.click('.demo-card.main');
await p.waitForSelector('.roster-grid');
res.cols = await p.locator('.rg-col span').allInnerTexts();
res.rows = await p.locator('.rg-row span').allInnerTexts();
res.cards = await p.locator('.rs-card').count();
res.chips = await p.locator('.rs-chip').allInnerTexts();
res.first = await p.locator('.rs-card').first().innerText();
await p.locator('.home-sec.roster').scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/1-grid.png`, fullPage: true });
await p.click('.rs-chip:nth-child(2)');
res.allCards = await p.locator('.rs-card').count();
res.past = await p.locator('.rs-card.past').count();
await p.click('.rs-chip:nth-child(1)');
await p.fill('.roster-search', 'jp');
res.search = await p.locator('.rs-card .rs-name').allInnerTexts();
await p.fill('.roster-search', '');
await p.click('.rs-card:has-text("Mina K")');
await p.waitForFunction(() => location.hash.startsWith('#/b/'));
res.opened = await p.evaluate(() => location.hash);
await p.setViewportSize({ width: 390, height: 800 });
await p.goto(`${BASE}/#/`);
await p.waitForSelector('.roster-grid');
await p.screenshot({ path: `${OUT}/2-phone.png` });
res.errs = errs;
console.log(JSON.stringify(res, null, 1));
await b.close();
